from ultralytics import YOLO

model = YOLO('./model/yolov8s.pt') # 替換為 's' 或 'n' 版本，筆電友善

# 開始訓練 (目標: 穩定性與準確性)
model.train(data='./dataset/data.yaml',
    # ==========================================
    # 階段 1：基礎訓練 (Prototype & Sanity Check)
    # 目標：快速跑通流程，確認資料標記沒錯，硬體能跑。
    # ==========================================
    epochs=100,      # [加速] 訓練輪數。
                     # 教學點：設定較少輪數（如 100 甚至 50），目的是在 1 小時內確認模型「學得起來」，
                     # 避免跑了 300 輪才發現標註錯誤，浪費大量算力時間。
    
    imgsz=720,       # [加速/權衡] 影像輸入尺寸。
                     # 教學點：尺寸越小跑越快。720 是一個平衡點，如果為了極致速度測試可降至 640；
                     # 但若要看清細節，720 是最低門檻。
    
    batch=8,         # [加速] 批次大小。
                     # 教學點：這是物理加速的關鍵。數值設越大，GPU 平行運算效率越高，訓練時間越短。
                     # (教學員觀察顯存 VRAM，沒滿就往上加)。

    # ==========================================
    # 階段 2：基礎驗證設定 (Validation & Metrics)
    # 目標：設定「什麼樣的標準」才算是一個好模型。
    # ==========================================
    conf=0.25,       # [過濾效率] 信心度閾值。
                     # 教學點：推論時過濾掉信心低於 25% 的雜訊框。
                     # 設定太低會導致運算量增加（處理一堆無效框）；設定太高會漏檢。
    
    iou=0.5,         # [過濾效率] 重疊閾值 (NMS)。
                     # 教學點：控制刪除重複框的嚴格程度。
                     # 在驗證階段，這參數不影響訓練速度，但影響「評估分數」出來的速度與準度。

    # ==========================================
    # 階段 3：輕量資料增強 (Generalization)
    # 目標：讓模型適應環境變化，省去蒐集不同環境資料的時間。
    # ==========================================
    hsv_h=0.015,     # [省時] 色相 (Hue) 微調。
                     # 教學點：模擬不同燈光色溫（冷光/暖光）。
                     # 優勢：不用真的去蒐集「黃光下」或「白光下」的照片，模型也能適應。
    
    hsv_s=0.7,       # [省時] 飽和度 (Saturation) 調整。
                     # 教學點：模擬物體褪色、生鏽或鮮豔度的變化。
    
    hsv_v=0.4,       # [省時] 明度 (Value) 調整。
                     # 教學點：模擬白天、陰天或陰影下的亮度。
                     # 優勢：極大減少為了「光線不同」而需重新拍攝資料的時間成本。
    
    scale=0.5,       # [效率] 隨機縮放 (+/- 50%)。
                     # 教學點：讓模型看過「大物件」與「小物件」。
                     # 優勢：不用刻意去拍「遠距離」或「近距離」的照片，程式自動幫你生成。
    
    translate=0.1,   # [效率] 隨機平移 (10%)。
                     # 教學點：模擬物件只露出一部分在畫面邊緣的情況。

    # ==========================================
    # 階段 4：進階資料增強 (Robustness & Final Polish)
    # 目標：針對高難度場景（遮擋、堆疊、歪斜）進行極限訓練。
    # ==========================================
    mosaic=1.0,      # [加速收斂] 馬賽克增強 (拼圖)。
                     # 教學點：一次把 4 張圖拼成 1 張給模型看。
                     # 優勢：豐富了背景資訊，讓模型訓練收斂速度變快，對小物件偵測特別有效。
    
    mixup=0.2,       # [品質] 混合增強 (疊圖)。
                     # 教學點：讓兩張圖半透明重疊。
                     # 優勢：增加對「重疊/透明/模糊物件」的抗干擾能力。
    
    degrees=10.0,    # [品質] 隨機旋轉 (+/- 10度)。
                     # 教學點：模擬物件歪斜或鏡頭不正。
                     # 這是解決「非水平物件」最核心的參數，省去標註旋轉框的時間。
    
    # 注意：進階階段的資源取捨
    batch=6,         # [權衡] 批次調小。
                     # 教學點：因為開啟了 Mosaic 和 Mixup，運算變複雜，顯存消耗變大。
                     # 為了防止訓練中斷 (OOM)，這時候必須犧牲一點速度，調小 Batch size。
    
    close_mosaic=10, # [品質] 關閉馬賽克 (最後 10 輪)。
                     # 教學點：訓練最後階段，關閉拼圖功能，讓模型看幾眼「正常的完整大圖」。
                     # 優勢：這通常能讓準確度 (mAP) 在最後時刻再往上衝刺 1%~2%。
    
    project='Steps_Training',
    name='Step_stage',)

print("訓練完成，模型儲存於 runs/detect/retrain_simple/")
